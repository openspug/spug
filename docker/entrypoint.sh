#!/bin/bash
# Entrypoint of the all-in-one image (Dockerfile at the repository root).
#
# On every start: sync the code baked into the image (/opt/spug) to the /data volume,
# generate spug/overrides.py once, wait for the database, apply schema changes, create the
# first admin account if there is none, then hand over to supervisord.
# Nothing here downloads anything.
set -euo pipefail

SRC=/opt/spug
APP=/data/spug
API=$APP/spug_api

log() { echo "[spug] $*"; }

# Docker engines older than 20.10.10 reject clone3 with EPERM, so glibc in this image cannot
# start threads at all; say so instead of letting every service fail in its own way.
if ! python3 -c 'import threading; t = threading.Thread(target=lambda: None); t.start(); t.join()' 2> /dev/null; then
    echo "[spug] ERROR: cannot start threads in this container. This usually means the Docker engine" \
         "is older than 20.10.10, whose seccomp profile blocks the clone3 syscall. Upgrade Docker," \
         "or run the container with --security-opt seccomp=unconfined." >&2
    exit 1
fi

# The legacy openspug/spug 3.x image ran MariaDB inside the container and kept it in
# /data/mysql. This image needs an external database, so leave such a volume untouched.
if [ -d /data/mysql ] || grep -qs 'mysql.sock' "$API/spug/overrides.py"; then
    cat >&2 <<'EOF'
[spug] ERROR: this /data volume belongs to the legacy all-in-one image (Spug 3.x with a
built-in MariaDB in /data/mysql). Spug 4 images use a separate database container, so this
container will not start on it. Nothing in the volume has been changed.

  - to keep running 3.x, use the image openspug/spug:3.3.2
  - to move to 4.x, see https://ops.spug.cc/en/docs/install-docker/
EOF
    exit 1
fi

# migrations are generated on the spot (they are not shipped), so they live in the volume
# next to the code they were generated from and must survive the sync
old_version=$(sed -n "s/^SPUG_VERSION = '\(.*\)'/\1/p" "$API/spug/settings.py" 2>/dev/null || true)
new_version=$(sed -n "s/^SPUG_VERSION = '\(.*\)'/\1/p" "$SRC/spug_api/spug/settings.py")
if [ -z "$old_version" ]; then
    log "installing Spug $new_version into $APP"
elif [ "$old_version" != "$new_version" ]; then
    log "upgrading Spug $old_version -> $new_version"
fi
mkdir -p "$APP" /data/repos
rsync -a --delete \
    --exclude '/.git/' \
    --exclude '/spug_api/spug/overrides.py' \
    --exclude '/spug_api/apps/*/migrations/' \
    --exclude '/spug_api/db.sqlite3' \
    --exclude '/spug_api/logs/' \
    --exclude '/spug_api/storage/' \
    --exclude '/spug_api/repos/' \
    --exclude '__pycache__/' \
    "$SRC/" "$APP/"
mkdir -p "$API/logs" "$API/storage/transfer" "$API/storage/deploy"

if [ ! -f "$API/spug/overrides.py" ]; then
    secret_key=$(python3 -c 'import secrets; print(secrets.token_urlsafe(50))')
    cat > "$API/spug/overrides.py" <<EOF
# Generated by the Docker image on first start and kept across upgrades; add your own
# settings here. Database and time zone come from the container environment.
import os

DEBUG = False
ALLOWED_HOSTS = ['127.0.0.1']
SECRET_KEY = '${secret_key}'

_tz = os.environ.get('TZ', '')
if _tz and not _tz.startswith('/') and os.path.isfile('/usr/share/zoneinfo/' + _tz):
    TIME_ZONE = _tz

if os.environ.get('MYSQL_HOST'):
    DATABASES = {
        'default': {
            'ATOMIC_REQUESTS': True,
            'ENGINE': 'django.db.backends.mysql',
            'NAME': os.environ.get('MYSQL_DATABASE', 'spug'),
            'USER': os.environ.get('MYSQL_USER', 'spug'),
            'PASSWORD': os.environ.get('MYSQL_PASSWORD', ''),
            'HOST': os.environ['MYSQL_HOST'],
            'PORT': os.environ.get('MYSQL_PORT', '3306'),
            'OPTIONS': {
                'charset': 'utf8mb4',
                'sql_mode': 'STRICT_TRANS_TABLES',
            }
        }
    }
EOF
fi

cd "$API"
if [ -n "${MYSQL_HOST:-}" ]; then
    log "waiting for the database at $MYSQL_HOST:${MYSQL_PORT:-3306}"
    python3 - <<'EOF'
import os, sys, time
import MySQLdb

deadline = time.time() + int(os.environ.get('SPUG_DB_WAIT', '180'))
while True:
    try:
        MySQLdb.connect(
            host=os.environ['MYSQL_HOST'], port=int(os.environ.get('MYSQL_PORT') or 3306),
            user=os.environ.get('MYSQL_USER', 'spug'), passwd=os.environ.get('MYSQL_PASSWORD', ''),
            db=os.environ.get('MYSQL_DATABASE', 'spug'), connect_timeout=5,
        ).close()
        break
    except MySQLdb.OperationalError as e:
        # access denied / unknown database will not fix themselves by waiting
        if e.args and e.args[0] in (1044, 1045, 1049):
            sys.exit(f'[spug] ERROR: {e}. Check MYSQL_* in the environment; note that an existing '
                     'database volume keeps the password it was first created with.')
        if time.time() > deadline:
            sys.exit(f'[spug] ERROR: the database is still not reachable: {e}')
        time.sleep(2)
EOF
else
    log "MYSQL_HOST is not set, using SQLite at $API/db.sqlite3 (fine for a trial, use MySQL/MariaDB for real use)"
fi

python3 manage.py updatedb

has_user=$(python3 manage.py shell -c 'from apps.account.models import User; print("yes" if User.objects.exists() else "no")' | tail -n 1)
if [ "$has_user" = "no" ]; then
    admin_user=${SPUG_ADMIN_USER:-admin}
    admin_password=${SPUG_ADMIN_PASSWORD:-}
    generated=
    if [ -z "$admin_password" ]; then
        admin_password=$(python3 -c 'import secrets; print(secrets.token_urlsafe(12))')
        generated=1
    fi
    python3 manage.py user add -u "$admin_user" -p "$admin_password" -n 管理员 -s > /dev/null
    if [ -n "$generated" ]; then
        log "============================================================"
        log " created the admin account"
        log "   username: $admin_user"
        log "   password: $admin_password"
        log " (generated once; change it after logging in)"
        log "============================================================"
    else
        log "created the admin account '$admin_user' with SPUG_ADMIN_PASSWORD"
    fi
fi

log "starting services"
exec supervisord -c /etc/supervisord.conf
